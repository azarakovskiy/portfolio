#!/usr/bin/env python3
"""Publish trusted HTML fragments to committed, dependency-free blog pages."""

from dataclasses import dataclass
from datetime import date
from html import escape
import json
from pathlib import Path
import re
import sys
from tempfile import NamedTemporaryFile
from textwrap import indent
from urllib.parse import urlsplit


GENERATED = "<!-- Generated by scripts/publish_blog.py; edit posts/ and rerun. -->"
PREVIEW_START = "<!-- blog-preview:start -->"
PREVIEW_END = "<!-- blog-preview:end -->"
MONTHS = (
    "January", "February", "March", "April", "May", "June",
    "July", "August", "September", "October", "November", "December",
)


@dataclass(frozen=True)
class Post:
    slug: str
    title: str
    published: date
    tags: list[str]
    summary: str
    body: str


def read_post(path: Path, root: Path) -> Post:
    label = path.relative_to(root)
    slug = path.stem
    if slug == "index" or not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug):
        raise ValueError(f"{label}: slug must be lowercase words/numbers joined by hyphens, not 'index'")
    try:
        source = path.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as error:
        raise ValueError(f"{label}: could not read UTF-8 source: {error}") from error
    match = re.fullmatch(r"\s*<!--(.*?)-->(.*)", source, re.DOTALL)
    if not match:
        raise ValueError(f"{label}: begin with an HTML comment containing JSON metadata")
    try:
        metadata = json.loads(match[1])
    except json.JSONDecodeError as error:
        raise ValueError(f"{label}: invalid metadata JSON: {error}") from error
    if not isinstance(metadata, dict):
        raise ValueError(f"{label}: metadata must be a JSON object")
    for field in ("title", "summary"):
        value = metadata.get(field)
        if not isinstance(value, str) or not value.strip():
            raise ValueError(f"{label}: {field} must be a nonblank string")
    value = metadata.get("date")
    if not isinstance(value, str) or not re.fullmatch(r"[0-9]{4}-[0-9]{2}-[0-9]{2}", value):
        raise ValueError(f"{label}: date must use YYYY-MM-DD")
    try:
        published = date.fromisoformat(value)
    except ValueError as error:
        raise ValueError(f"{label}: date must be a real calendar date: {value}") from error
    tags = metadata.get("tags")
    if not isinstance(tags, list) or not tags or any(
        not isinstance(tag, str) or not tag.strip() for tag in tags
    ):
        raise ValueError(f"{label}: tags must be a nonempty list of nonblank strings")
    body = match[2]
    if not body.strip():
        raise ValueError(f"{label}: HTML body must not be blank")
    return Post(slug, metadata["title"].strip(), published, [tag.strip() for tag in tags],
                metadata["summary"].strip(), body)


def render_metadata(post: Post) -> str:
    published = post.published
    readable = f"{MONTHS[published.month - 1]} {published.day}, {published.year:04d}"
    tags = "".join(f"<li>{escape(tag)}</li>" for tag in post.tags)
    return (
        '<div class="post-meta">'
        f'<time datetime="{published.isoformat()}">{readable}</time>'
        f'<ul class="post-tags" aria-label="Tags">{tags}</ul></div>'
    )


def render_posts(posts: list[Post], homepage: bool = False) -> str:
    if not posts:
        return '<p class="blog-empty">No posts published yet.</p>'
    heading = "h3" if homepage else "h2"
    prefix = "blog/" if homepage else ""

    def read_link(post: Post) -> str:
        return (
            f'<a class="post-read-link" href="{prefix}{post.slug}/" '
            f'aria-label="Read post: {escape(post.title)}">'
            '<span class="post-read-label">Read post</span>'
            '<span aria-hidden="true">↗</span></a>'
        )

    latest = posts[0]
    feature = (
        '<article class="post-feature">\n'
        '  <div class="post-feature-copy">\n'
        f'    <{heading} class="post-title">{escape(latest.title)}</{heading}>\n'
        f'    <p class="post-summary">{escape(latest.summary)}</p>\n'
        '  </div>\n'
        '  <div class="post-feature-details">\n'
        f'    {read_link(latest)}\n'
        f'    {render_metadata(latest)}\n'
        '  </div>\n'
        '</article>'
    )
    rows = []
    for post in posts[1:]:
        rows.append(
            '<li><article class="post-supporting-post">\n'
            '  <header class="post-heading">\n'
            f'    <{heading} class="post-title">{escape(post.title)}</{heading}>\n'
            f'    {read_link(post)}\n'
            '  </header>\n'
            f'  <p class="post-summary">{escape(post.summary)}</p>\n'
            f'  {render_metadata(post)}\n'
            '</article></li>'
        )
    if not rows:
        return feature
    return feature + '\n<ol class="post-supporting">\n' + "\n".join(rows) + "\n</ol>"


def render_preview(posts: list[Post]) -> str:
    if not posts:
        return ""
    return (
        '<section class="blog-preview" id="blog" aria-labelledby="blog-title">\n'
        '  <div class="container">\n'
        '    <h2 class="route section-route" id="blog-title">/blog</h2>\n'
        + indent(render_posts(posts[:3], homepage=True), "    ") + '\n'
        '  </div>\n'
        '</section>'
    )


def render_header(header: str, depth: int) -> str:
    prefix = "../" * depth

    def rebase_link(match: re.Match) -> str:
        tag = match[0]
        href = re.search(r'\bhref="([^"]*)"', tag)
        if href:
            target = href[1]
            if target == "blog/":
                replacement = 'href="./" aria-current="page"' if depth == 1 else 'href="../"'
                tag = tag.replace(href[0], replacement, 1)
            elif target.startswith("#"):
                tag = tag.replace(href[0], f'href="{prefix}index.html{target}"', 1)
            elif not urlsplit(target).scheme and not target.startswith("//"):
                tag = tag.replace(href[0], f'href="{prefix}{target.lstrip("/")}"', 1)
        if 'class="site-brand"' in tag and 'aria-label=' not in tag:
            tag = tag[:-1] + ' aria-label="Alexey Zarakovskiy, portfolio">'
        return tag

    header = re.sub(r"<a\b[^>]*>", rebase_link, header)
    return re.sub(r'\s*<span class="header-section"[^>]*>.*?</span>', "", header, flags=re.DOTALL)


def render_page(title: str, description: str, header: str, main: str, depth: int) -> str:
    # Keep article whitespace intact, particularly inside preformatted code.
    return f'''<!doctype html>
{GENERATED}
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <meta name="description" content="{escape(description)}" />
    <meta name="color-scheme" content="light" />
    <title>{escape(title)} | Alexey Zarakovskiy</title>
    <link rel="stylesheet" href="{"../" * depth}styles.css" />
    <script src="{"../" * depth}contact-links.js" defer></script>
  </head>
  <body class="blog-page" id="top">
    <a class="skip-link" href="#main">Skip to content</a>
{indent(render_header(header, depth), "    ")}
    <main id="main" tabindex="-1" class="container blog-main">
{main}
    </main>
  </body>
</html>
'''


def render_listing(posts: list[Post]) -> str:
    return (
        '<p class="route">/blog</p>\n'
        '<h1 class="blog-index-title">Blog</h1>\n'
        + render_posts(posts)
    )


def render_article(post: Post) -> str:
    return (
        '<article class="blog-article">\n'
        '  <header class="article-heading">\n'
        f'    <h1>{escape(post.title)}</h1>\n'
        f'    <p class="post-summary">{escape(post.summary)}</p>\n'
        f'    {render_metadata(post)}\n'
        '  </header>\n'
        f'  <div class="prose">{post.body}</div>\n'
        '</article>'
    )


def write_page(path: Path, content: str) -> None:
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with NamedTemporaryFile(mode="w", encoding="utf-8", dir=path.parent,
                                prefix=".publish-", delete=False) as output:
            temporary = Path(output.name)
            output.write(content)
        temporary.chmod(0o644)
        temporary.replace(path)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def publish(root: Path) -> None:
    root = Path(root)
    posts = [read_post(path, root) for path in sorted((root / "posts").glob("*.html"))]
    posts.sort(key=lambda post: (-post.published.toordinal(), post.slug))
    homepage_path = root / "index.html"
    homepage = homepage_path.read_text(encoding="utf-8")
    if homepage.count(PREVIEW_START) != 1 or homepage.count(PREVIEW_END) != 1:
        raise ValueError("index.html: expected one blog-preview:start and blog-preview:end marker")
    header_match = re.search(r'<header class="site-header">.*?</header>', homepage, re.DOTALL)
    if not header_match:
        raise ValueError('index.html: missing <header class="site-header">')
    header = header_match[0].replace('href="blog/" hidden', 'href="blog/"')
    if not posts:
        header = header.replace('href="blog/"', 'href="blog/" hidden')
    homepage = homepage[:header_match.start()] + header + homepage[header_match.end():]
    before, _, remaining = homepage.partition(PREVIEW_START)
    _, end, after = remaining.partition(PREVIEW_END)
    if not end:
        raise ValueError("index.html: blog preview end marker must follow the start marker")
    updated_homepage = (
        before + PREVIEW_START + "\n" + indent(render_preview(posts), "      ")
        + "\n      " + PREVIEW_END + after
    )
    blog = root / "blog"
    pages = {
        blog / "index.html": render_page(
            "Blog", "Technical writing by Alexey Zarakovskiy.", header, render_listing(posts), 1
        ),
    }
    for post in posts:
        pages[blog / post.slug / "index.html"] = render_page(
            post.title, post.summary, header, render_article(post), 2
        )
    for path in pages:
        if path.exists() and GENERATED not in path.read_text(encoding="utf-8"):
            raise ValueError(f"{path.relative_to(root)}: refusing to replace a file not generated by the publisher")
    stale = [
        path for path in blog.glob("*/index.html")
        if path not in pages and GENERATED in path.read_text(encoding="utf-8", errors="replace")
    ]
    for path, content in pages.items():
        write_page(path, content)
    write_page(homepage_path, updated_homepage)
    for path in stale:
        path.unlink()
        try:
            path.parent.rmdir()
        except OSError:
            pass  # Keep directories containing assets or other user-authored files.


if __name__ == "__main__":
    try:
        publish(Path(__file__).resolve().parents[1])
    except (OSError, ValueError) as error:
        print(f"publish_blog: {error}", file=sys.stderr)
        raise SystemExit(1)
